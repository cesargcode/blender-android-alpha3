"""Build a fixture plus freshly extracted production C++ input functions.

Usage: python entrega/tests/run_host_tests.py
The source file, stub class declarations, selected function names and assertion
driver are specified in host_test_config.json. Nothing is downloaded by this
script. Build logs, the extracted translation unit, and result metadata are
retained under entrega/tests/build for review.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

from extract_cpp import extract_braced_declaration, extract_function, extraction_self_test


def extract_wm_text_mapping(source_root: Path) -> tuple[str, dict]:
    """Compile the actual GHOST->WM mapping/enums, separate from interface doubles."""
    paths = {
        "ghost_types": source_root / "intern/ghost/GHOST_Types.hh",
        "wm_types": source_root / "source/blender/windowmanager/wm_event_types.hh",
        "wm_events": source_root / "source/blender/windowmanager/intern/wm_event_system.cc",
    }
    texts = {name: path.read_text(encoding="utf-8") for name, path in paths.items()}
    ghost_enum, _ = extract_braced_declaration(texts["ghost_types"], "enum GHOST_TKey")
    wm_enum, _ = extract_braced_declaration(texts["wm_types"], "enum wmEventType")
    mapping, _ = extract_function(texts["wm_events"], "wm_event_type_from_ghost_key")
    lines = texts["wm_types"].splitlines()
    start = next(i for i, line in enumerate(lines)
                 if line.startswith("#define ISKEYBOARD(event_type)"))
    macro = [lines[start]]
    while macro[-1].endswith("\\"):
        macro.append(lines[start + len(macro)])
    chunks = [
        "namespace wm_text_mapping_test {",
        ghost_enum, wm_enum, "\n".join(macro),
        "static void BLI_assert_unreachable() { std::abort(); }",
        "#define CLOG_WARN(...) ((void)0)", mapping, "#undef CLOG_WARN",
        "static bool unknown_key_accepts_text() {\n"
        "  const wmEventType type = wm_event_type_from_ghost_key(GHOST_kKeyUnknown);\n"
        "  return type != EVENT_NONE && type == EVT_UNKNOWNKEY && ISKEYBOARD(type);\n"
        "}",
        "#undef ISKEYBOARD",
        "} // namespace wm_text_mapping_test",
    ]
    evidence = {name: {"path": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()}
                for name, path in paths.items()}
    return "\n".join(chunks), evidence


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path)
    parser.add_argument("--source", type=Path,
                        help="Override the production GHOST_SystemAndroid.cc path")
    parser.add_argument("--compiler", type=Path)
    args = parser.parse_args()
    here = Path(__file__).resolve().parent
    root = here.parent.parent
    config_path = args.config or here / "host_test_config.json"
    config = json.loads(config_path.read_text(encoding="utf-8"))
    source_path = (args.source or root / config["source"]).resolve()
    compiler = (args.compiler or root / "tools/ziglang/ziglang/zig.exe").resolve()
    if not compiler.is_file():
        raise FileNotFoundError(f"C++ compiler is unavailable: {compiler}")
    extraction_self_test()
    build = here / "build"
    build.mkdir(exist_ok=True)
    source_bytes = source_path.read_bytes()
    source = source_bytes.decode("utf-8")
    wm_mapping, wm_mapping_evidence = extract_wm_text_mapping(source_path.parents[3])
    chunks = [
        '// Generated by run_host_tests.py from the current production source.\n',
        '#include "../android_input_fixture.hh"\n',
        (here / config["declarations"]).read_text(encoding="utf-8"),
        wm_mapping,
    ]
    extracted = []
    source_label = str(source_path).replace("\\", "/")
    for prefix in config.get("production_declarations", []):
        definition, line = extract_braced_declaration(source, prefix)
        chunks.append(f'\n#line {line} "{source_label}"\n{definition}\n')
        extracted.append({"declaration": prefix, "source_line": line})
    for name in config["functions"]:
        definition, line = extract_function(source, name)
        chunks.append(f'\n#line {line} "{source_label}"\n{definition}\n')
        extracted.append({"name": name, "source_line": line})
    test_path = here / config["assertions"]
    test_label = str(test_path).replace("\\", "/")
    chunks.append(f'\n#line 1 "{test_label}"\n')
    chunks.append(test_path.read_text(encoding="utf-8"))
    translation_unit = build / "android_input_regression.cc"
    translation_unit.write_text("\n".join(chunks), encoding="utf-8")
    executable = build / "android_input_regression.exe"
    command = [str(compiler), "c++", "-std=c++17", "-O0", "-g",
               "-Wall", "-Wextra", "-Wno-unused-function",
               str(translation_unit), "-o", str(executable)]
    environment = os.environ.copy()
    environment["ZIG_GLOBAL_CACHE_DIR"] = str(build / "zig-global-cache")
    environment["ZIG_LOCAL_CACHE_DIR"] = str(build / "zig-local-cache")
    result = subprocess.run(command, capture_output=True, text=True, env=environment)
    compile_log = result.stdout + result.stderr
    (build / "compile.log").write_text(compile_log, encoding="utf-8")
    metadata = {
        "source": str(source_path),
        "source_sha256": hashlib.sha256(source_bytes).hexdigest(),
        "functions": extracted,
        "wm_text_mapping_sources": wm_mapping_evidence,
        "compiler": str(compiler),
        "compile_returncode": result.returncode,
        "scope": "Host C++ interface doubles; not an Android APK build/device test",
    }
    if result.returncode:
        print(compile_log)
        (build / "result.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
        return result.returncode
    test_result = subprocess.run([str(executable)], capture_output=True, text=True,
                                 cwd=build, env=environment)
    test_log = test_result.stdout + test_result.stderr
    (build / "test.log").write_text(test_log, encoding="utf-8")
    metadata["test_returncode"] = test_result.returncode
    metadata["test_output"] = test_log
    (build / "result.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
    print(test_log, end="")
    return test_result.returncode


if __name__ == "__main__":
    sys.exit(main())
